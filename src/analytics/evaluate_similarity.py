"""Run `find_similar` for fixed well-known 2015/16 players and write docs/similarity_eval.md.

This is a look-at-the-output check, not a benchmark: there is no ground truth for "similar
player", so the document shows the lists and their explanations. The player set is fixed in
advance (`EVAL_PLAYERS`) and the algorithm is not tuned to any of them.

Run: `python -m src.analytics.evaluate_similarity`
"""

from __future__ import annotations

from src.utils import disk_bootstrap  # isort: skip  # noqa: F401  (must be first)

import argparse
from datetime import date
from pathlib import Path

from src.analytics.similarity import (
    EXCLUDED_FEATURES,
    VARIANCE_TARGET,
    find_similar,
)
from src.models.similarity import SimilarityResult, SimilarPlayer
from src.transform.normalize import DEFAULT_LEAGUE, DEFAULT_SEASON
from src.utils.config import PROJECT_ROOT
from src.utils.logging import logger

OUTPUT = PROJECT_ROOT / "docs" / "similarity_eval.md"

# (name to look up, position group the brief expected). The brief's labels are expectations, not
# inputs: the group actually used is the one in the data (`position_group_fine`).
EVAL_PLAYERS: tuple[tuple[str, str], ...] = (
    ("Petr Čech", "GK"),
    ("Wes Morgan", "CB"),
    ("Robert Huth", "CB"),
    ("Christian Fuchs", "FB"),
    ("Kyle Walker", "FB"),
    ("N'Golo Kanté", "DM"),
    ("Mesut Özil", "CM"),
    ("Riyad Mahrez", "CM"),
    ("Jamie Vardy", "ST"),
    ("Harry Kane", "ST"),
)

HEADER = """# Similarity engine: evaluation on 2015/16 EPL

Generated by `python -m src.analytics.evaluate_similarity` on {today}. Data: StatsBomb Open Data,
Premier League 2015/16, {n_players} fixed players, top 10 each.

## What this is, and is not

A **heuristic** ranking. There is no ground truth for "similar player", so nothing here is scored
for accuracy and the model must not be described as accurate. This file shows the output so a
person can judge whether it looks sensible. The evaluation players were fixed before the run and
the algorithm was not tuned to any of them.

Method (`src/analytics/similarity.py`): features for the player's `position_group_fine` (per-90
rates and ratios only, no raw totals; yellow/red cards excluded as chance-driven) -> z-score
**within the position group** -> PCA keeping >= {variance:.0%} of the variance -> cosine similarity
on the PCA vectors. Players are only compared with players of the same fine position group.

Reading the tables: **similarity** is a cosine (1 = same direction in the PCA space). **Shared**
lists the three metrics that add most to that similarity (both players unusual in the same
direction on them, with each player's within-position z-score, target first: `z -1.2 / -0.9`
means both are LOW on it, not high); **differs** lists the metric where the pair differs most
(feature delta carried through the PCA loadings). Both explain the score; they are not extra
evidence.

Limits that apply to every list: a single season; one league; the season table only holds players
with 900+ minutes; the group is the position with the most minutes, so mixed-role players are
searched only within that one group; the descriptive proxy metrics (positioning, receiving) are
included as *style* features and describe team context as much as the player; no ages (StatsBomb
has none), so `max_age` cannot be used.
"""


def _row(p: SimilarPlayer) -> str:
    diff = p.differing_metrics[0]
    differs = f"{diff.metric} ({diff.target_value} vs {diff.candidate_value})"
    # z = within-position z-score of each player; both negative means both are low, not high.
    shared = ", ".join(
        f"{m.metric} (z {m.target_z:+.1f} / {m.candidate_z:+.1f})" for m in p.shared_metrics
    )
    return f"| {p.rank} | {p.player_name} | {p.team} | {p.similarity:.3f} | {shared} | {differs} |"


def render(entries: list[tuple[str, str, SimilarityResult]], notes: str) -> str:
    """The markdown document for a list of (query, expected group, result)."""
    parts = [HEADER.format(today=date.today().isoformat(), n_players=len(entries),
                           variance=VARIANCE_TARGET)]  # fmt: skip
    parts.append("## Summary\n")
    parts.append(
        "| Player | Brief expected | Group in data | Share of minutes | Group size | Features | "
        "PCA components | Variance kept |\n"
        "|---|---|---|---|---|---|---|---|"
    )
    for _, expected, r in entries:
        flag = "" if expected == r.position_group_fine else " (differs)"
        parts.append(
            f"| {r.target_name} ({r.target_team}) | {expected} | {r.position_group_fine}{flag} | "
            f"{r.position_group_fine_share:.0%} | {r.group_size} | {len(r.features_used)} | "
            f"{r.n_components} | {r.explained_variance:.1%} |"
        )
    parts.append("")
    for _, _, r in entries:
        parts.append(f"## {r.target_name} ({r.target_team}), {r.position_group_fine}\n")
        for w in r.warnings:
            parts.append(f"> {w}\n")
        parts.append("| # | Player | Team | Similarity | Shared (top 3) | Differs most |")
        parts.append("|---|---|---|---|---|---|")
        parts += [_row(s) for s in r.similar]
        parts.append("")
    parts.append(notes)
    parts.append(
        f"\n---\nExcluded from every feature set: {', '.join(sorted(EXCLUDED_FEATURES))}. "
        "Features per group are `profile.RELEVANT_METRICS` for that group.\n"
    )
    return "\n".join(parts)


def _notes_text() -> str:
    """Reviewer notes: read from docs/similarity_eval_notes.md if it exists."""
    notes = OUTPUT.with_name("similarity_eval_notes.md")
    return notes.read_text(encoding="utf-8") if notes.exists() else ""


def run(season: str = DEFAULT_SEASON, league: str = DEFAULT_LEAGUE) -> Path:
    entries = []
    for query, expected in EVAL_PLAYERS:
        result = find_similar(query, season=season, n=10, league=league)
        entries.append((query, expected, result))
        logger.info(
            "{q}: {g}, top match {m} ({s:.3f})", q=query, g=result.position_group_fine,
            m=result.similar[0].player_name, s=result.similar[0].similarity,
        )  # fmt: skip
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(render(entries, _notes_text()), encoding="utf-8", newline="\n")
    return OUTPUT


def _main() -> None:
    parser = argparse.ArgumentParser(description="Write docs/similarity_eval.md.")
    parser.add_argument("--season", default=DEFAULT_SEASON)
    parser.add_argument("--league", default=DEFAULT_LEAGUE)
    args = parser.parse_args()
    print(f"wrote {run(args.season, args.league)}")


if __name__ == "__main__":
    _main()
